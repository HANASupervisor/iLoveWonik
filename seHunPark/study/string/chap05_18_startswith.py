'''
str. startswith(value, [start, end])
 문자열이 특정 문자열로 시작하는지 확인\
 start, end: 선택 사항

str. endswith(value, [start, end])
 문자열이 특정 문자열로 끝나는지 확인
 
'''
s1 = 'hello.py'

print("s1.startwith('Hello'):", s1.startswith('Hello'))
print("s1.endswith('.py'):",s1.endswith('.py'))

s2 = 'Welcom to my world.'
print("s2.endswith('.'):",s2.endswith('.'))



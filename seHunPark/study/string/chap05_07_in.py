'''
in : 포함 여부(True/False)

'''
# in 연산자

msg = 'Love will find a way.'
print("Love" in msg)
print("love" in msg)

'''
not in : 데이터가 없으면 True, 있으면 False
'''

# not in 연산자
msg = input("문자열을 입력하시오: ")

if 'a' not in msg:
    print('a가 포함되어 있지 않음')
else:
    print('a가 포함되어 있음')

